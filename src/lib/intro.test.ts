import { stripIntro } from '@/lib/intro';

describe('stripIntro', () => {
  it.each([
    ['напомни мне что купить хлеб', 'купить хлеб'],
    ['Напомни мне чтобы я купил хлеб', 'Купить хлеб'],
    ['слушай, не забудь мне напомнить, что надо купить хлеб', 'купить хлеб'],
    ['ну так вот, надо купить хлеб', 'купить хлеб'],
    ['запиши : купить молоко', 'купить молоко'],
    ['запиши мне купить молоко', 'купить молоко'],
    ['запиши о том что купить молоко', 'купить молоко'],
    ['напомнить себе позвонить маме', 'позвонить маме'],
    ['Пожалуйста, напомни-ка позвонить маме', 'Позвонить маме'],
    ['будь добр, поставь будильник встать в 7', 'встать в 7'],
    ['Добавь задачу сдать отчёт', 'Сдать отчёт'],
    ['Задача — сдать отчёт', 'Сдать отчёт'],
    ['А ну-ка, запиши мне пожалуйста позвонить шефу', 'Позвонить шефу'],
    ['а ну ка запиши мне позвонить шефу', 'позвонить шефу'],
    ['запиши-ка купить молоко', 'купить молоко'],
    ['слушай-ка, напомните-ка мне про встречу', 'про встречу'],
    ['напомни что бы купить хлеб', 'купить хлеб'],
  ])('«%s» → «%s»', (title, expected) => {
    expect(stripIntro(title)).toBe(expected);
  });

  it.each([
    ['Мне нужно что бы ты записал мне что бы я позвонил шефу', 'Позвонить шефу'],
    ['мне нужно чтобы ты записал мне что нужно позвонить шефу', 'позвонить шефу'],
    ['Я хочу, чтобы ты напомнил мне купить хлеб', 'Купить хлеб'],
    ['хочу чтобы ты мне записала: сдать отчёт', 'сдать отчёт'],
    ['Можешь напомнить мне позвонить маме', 'Позвонить маме'],
    ['не могла бы ты, пожалуйста, записать купить молоко', 'купить молоко'],
    ['ты можешь мне напомнить о том что надо оплатить интернет', 'оплатить интернет'],
    ['так, можешь записать мне купить корм', 'купить корм'],
  ])('обращение: «%s» → «%s»', (title, expected) => {
    expect(stripIntro(title)).toBe(expected);
  });

  it.each([
    ['напомни чтобы я позвонила маме', 'позвонить маме'],
    ['напомни нам чтобы мы забрали посылку', 'забрать посылку'],
    ['напомни чтобы я не опоздал на поезд', 'не опоздать на поезд'],
    ['напомни чтобы я записался к врачу', 'записаться к врачу'],
    ['напомни, чтобы я купил хлеб.', 'купить хлеб.'],
    ['напомни чтобы я поел', 'поел'],
    ['напомни чтобы я пошёл в магазин', 'пошёл в магазин'],
  ])('«чтобы я купил» → «купить»: «%s» → «%s»', (title, expected) => {
    expect(stripIntro(title)).toBe(expected);
  });

  it.each([
    'вот это да',
    'да ладно',
    'а потом в магазин',
    'и сходить в магазин',
    'мне купить хлеб',
    'что купить на ужин',
    'напомните-ка нам',
    'надо, надо',
    'запиши ребёнка к врачу',
    'задача по физике',
    'напомнить Пете',
    'купить хлеб',
    'хочу пиццу',
    'хочу чтобы Петя позвонил',
    'можешь идти',
    'можешь записать ребёнка к врачу',
    'купил хлеб',
    'чтобы ты знал',
    'я купил хлеб',
    '',
  ])('«%s» — как было', (title) => {
    expect(stripIntro(title)).toBe(title);
  });
});
