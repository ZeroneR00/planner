import { stripIntro } from '@/lib/intro';

describe('stripIntro', () => {
  it.each([
    ['напомни мне что купить хлеб', 'купить хлеб'],
    ['Напомни мне чтобы я купил хлеб', 'Купил хлеб'],
    ['слушай, не забудь мне напомнить, что надо купить хлеб', 'купить хлеб'],
    ['ну так вот, надо купить хлеб', 'купить хлеб'],
    ['запиши : купить молоко', 'купить молоко'],
    ['запиши мне купить молоко', 'купить молоко'],
    ['запиши о том что купить молоко', 'купить молоко'],
    ['напомнить себе позвонить маме', 'позвонить маме'],
    ['Пожалуйста, напомни-ка позвонить маме', 'Позвонить маме'],
    ['будь добр, поставь будильник встать в 7', 'встать в 7'],
    ['Добавь задачу сдать отчёт', 'Сдать отчёт'],
    ['Задача — сдать отчёт', 'Сдать отчёт'],
    ['А ну-ка, запиши мне пожалуйста позвонить шефу', 'Позвонить шефу'],
    ['а ну ка запиши мне позвонить шефу', 'позвонить шефу'],
    ['запиши-ка купить молоко', 'купить молоко'],
    ['слушай-ка, напомните-ка мне про встречу', 'про встречу'],
  ])('«%s» → «%s»', (title, expected) => {
    expect(stripIntro(title)).toBe(expected);
  });

  it.each([
    'вот это да',
    'да ладно',
    'а потом в магазин',
    'и сходить в магазин',
    'мне купить хлеб',
    'что купить на ужин',
    'напомните-ка нам',
    'надо, надо',
    'запиши ребёнка к врачу',
    'задача по физике',
    'напомнить Пете',
    'купить хлеб',
    '',
  ])('«%s» — как было', (title) => {
    expect(stripIntro(title)).toBe(title);
  });
});
