describe('parseWhen: особые случаи', () => {
  it('берётся только первая фраза по порядку матчеров', () => {
    expect(parse('завтра во вторник')).toMatchObject({ title: 'завтра', date: '2026-10-20' });
  });

  it('лишние пробелы схлопываются', () => {
    expect(parse('  купить   хлеб  завтра ').title).toBe('купить хлеб');
  });

  it('голое «в 9» не в конце пропускается, но следующее в конце — время', () => {
    expect(parse('разбить в 2 этапа в 9')).toMatchObject({ title: 'разбить в 2 этапа', time: '09:00' });
  });
});

describe('timePhrase', () => {
  it.each([
    ['15:00', 'в 15:00'],
    ['09:00', 'в 9:00'],
    ['03:00', 'в 03:00'],
    ['00:00', 'в 0:00'],
  ])('%s → «%s»', (time, phrase) => {
    expect(timePhrase(time)).toBe(phrase);
  });

  it.each(['00:00', '03:00', '07:30', '09:00', '13:00', '23:59'])('%s разбирается обратно', (time) => {
    expect(parse(`созвон ${timePhrase(time)}`)).toMatchObject({ title: 'созвон', time });
  });
});
